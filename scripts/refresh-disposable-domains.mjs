#!/usr/bin/env node
/**
 * Regenerates lib/data/disposable-domains.ts from the public disposable-email
 * list, at one pinned commit.
 *
 * The list is disposable-email-domains/disposable-email-domains on GitHub,
 * file disposable_email_blocklist.conf. Its LICENSE.txt is "CC0 1.0 Universal
 * (CC0 1.0) Public Domain Dedication", and its README says it may be copied,
 * modified and used without asking, so bundling it needs no notice. Checked at
 * the pinned commit below.
 *
 * Pinned rather than "main", because this list decides which addresses the
 * cast route turns away. A refresh is a change somebody reviews in a diff,
 * never something a build does on its own: an upstream mistake that listed a
 * real provider would otherwise refuse its voters on the next deploy without
 * anybody having read it. The unit tests then check the result (no consumer
 * provider on it, no public suffix on it) before it can ship.
 *
 * To refresh: set COMMIT to a newer commit of the upstream repository, run
 *
 *   node scripts/refresh-disposable-domains.mjs
 *
 * read the diff of lib/data/disposable-domains.ts, and run the tests. A wrongly
 * listed real domain is undone with DISPOSABLE_EXCEPTIONS in lib/vote-domain.ts,
 * not by editing the generated file, so the next refresh cannot bring it back.
 *
 * --file <path> reads a local copy instead of fetching, for a machine with no
 * network. The copy must be the pinned commit's file; its sha256 is written
 * into the generated header, so a reviewer can compare it with upstream.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { getDomain } from "tldts";

const REPO = "disposable-email-domains/disposable-email-domains";
const COMMIT = "0655284b6a0b5c674789756ce8b6b35441b800bc";
const FILE = "disposable_email_blocklist.conf";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "lib/data/disposable-domains.ts");

/** The same shape the block table's CHECK accepts: lowercase labels, a dot. */
const DOMAIN = /^[a-z0-9-]+(\.[a-z0-9-]+)+$/;

async function source() {
  const at = process.argv.indexOf("--file");
  if (at !== -1) {
    const path = process.argv[at + 1];
    if (!path) throw new Error("--file needs a path");
    return readFileSync(path, "utf8");
  }
  const url = `https://raw.githubusercontent.com/${REPO}/${COMMIT}/${FILE}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  return response.text();
}

const raw = await source();
const sha256 = createHash("sha256").update(raw).digest("hex");

const entries = raw
  .split("\n")
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith("#"));

/*
 * Refuse to write anything a reviewer would have to catch by eye. Every entry
 * has to be a domain name (it is pasted into a template literal, so a stray
 * backtick or ${ would be code), and none may be a public suffix: the cast
 * route refuses the host and every parent of it, so a listed "com.ng" would
 * turn away every company in Nigeria.
 */
const problems = [];
const seen = new Set();
for (const entry of entries) {
  if (!DOMAIN.test(entry)) problems.push(`not a domain: ${JSON.stringify(entry)}`);
  else if (getDomain(entry, { allowPrivateDomains: false }) === null) {
    problems.push(`a public suffix: ${entry}`);
  }
  if (seen.has(entry)) problems.push(`listed twice: ${entry}`);
  seen.add(entry);
}
if (problems.length > 0) {
  console.error(problems.slice(0, 20).join("\n"));
  process.exit(1);
}

const body = `/*
 * Generated by scripts/refresh-disposable-domains.mjs. Do not edit by hand:
 * the next refresh would undo it. A wrongly listed real domain goes in
 * DISPOSABLE_EXCEPTIONS in lib/vote-domain.ts instead.
 *
 * Source: https://github.com/${REPO}
 *         ${FILE} at commit ${COMMIT}
 *         sha256 ${sha256}
 * License: CC0 1.0 Universal (public domain dedication), per the upstream
 *          LICENSE.txt at that commit.
 * Entries: ${entries.length}
 *
 * One newline-joined string rather than an array literal: nine thousand
 * string literals cost the type checker and the bundler far more than one
 * template string, and the lookup builds its Set once, on first use.
 */

export const DISPOSABLE_DOMAINS_COMMIT = "${COMMIT}";

export const DISPOSABLE_DOMAINS = \`${entries.join("\n")}\`;
`;

writeFileSync(OUT, body);
console.log(`Wrote ${entries.length} domains from ${COMMIT.slice(0, 7)} to lib/data/disposable-domains.ts`);
